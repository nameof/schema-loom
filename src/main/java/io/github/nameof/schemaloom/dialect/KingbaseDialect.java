package io.github.nameof.schemaloom.dialect;

import io.github.nameof.schemaloom.api.*;
import io.github.nameof.schemaloom.driver.DatabaseConnectionInfo;
import io.github.nameof.schemaloom.metadata.ColumnInfo;
import io.github.nameof.schemaloom.metadata.QualifiedTableName;

import java.util.*;

// 人大金仓（KingbaseES）基于 PostgreSQL，类型系统和 SQL 语法与 PostgreSQL 高度兼容。
final class KingbaseDialect extends AbstractDialect {
    private final Map<LogicalType, DatabaseTypeMapping> mappings = mappings();

    @Override protected String quoteChar() { return "\""; }
    @Override public DatabaseTypeMapping mapping(LogicalType type) { return mappings.get(type); }
    @Override protected String identityColumn(ColumnInfo column) { return "GENERATED BY DEFAULT AS IDENTITY"; }

    @Override
    protected String defaultValue(ColumnInfo column) {
        String value = column.getDefaultValue();
        if (value != null && value.trim().matches("'(?:''|[^'])*'::(?i:(?:character varying|varchar(?:\\(\\d+\\))?|text))"))
            return value.trim().substring(0, value.trim().indexOf("::"));
        return super.defaultValue(column);
    }
    @Override protected String generatedColumn(ColumnInfo column) { return super.generatedColumn(column) + " STORED"; }

    @Override public String renameTableSql(String table, String newTable) {
        return "ALTER TABLE " + table + " RENAME TO " + lastIdentifier(newTable);
    }

    private String lastIdentifier(String qualified) {
        boolean quoted = false;
        int separator = -1;
        for (int i = 0; i < qualified.length(); i++) {
            char c = qualified.charAt(i);
            if (c == '"') {
                if (quoted && i + 1 < qualified.length() && qualified.charAt(i + 1) == '"') { i++; continue; }
                quoted = !quoted;
            } else if (c == '.' && !quoted) separator = i;
        }
        return separator < 0 ? qualified : qualified.substring(separator + 1);
    }

    @Override
    public ViewDefinitionQuery viewDefinitionQuery(DatabaseConnectionInfo source, QualifiedTableName view) {
        String schema = view.getSchema() == null ? "public" : view.getSchema();
        return new ViewDefinitionQuery("SELECT pg_get_viewdef(?::regclass, true)",
                Collections.singletonList(schema + "." + view.getTable()));
    }

    private Map<LogicalType, DatabaseTypeMapping> mappings() {
        EnumMap<LogicalType, DatabaseTypeMapping> m = new EnumMap<LogicalType, DatabaseTypeMapping>(LogicalType.class);
        m.put(LogicalType.BOOLEAN, DatabaseTypeMapping.supported("BOOLEAN"));
        m.put(LogicalType.INT16, DatabaseTypeMapping.supported("SMALLINT"));
        m.put(LogicalType.INT32, DatabaseTypeMapping.supported("INTEGER"));
        m.put(LogicalType.INT64, DatabaseTypeMapping.supported("BIGINT"));
        m.put(LogicalType.DECIMAL, DatabaseTypeMapping.supported(f -> "NUMERIC(" +
                Math.min(f.getPrecision() == null ? 1000 : f.getPrecision(), 1000) + "," +
                Math.min(f.getScale() == null ? 0 : f.getScale(), 1000) + ")"));
        m.put(LogicalType.FLOAT32, DatabaseTypeMapping.supported("REAL"));
        m.put(LogicalType.FLOAT64, DatabaseTypeMapping.supported("DOUBLE PRECISION"));
        m.put(LogicalType.STRING, DatabaseTypeMapping.supported(f ->
                f.getLength() != null && f.getLength() > 0 ? "VARCHAR(" + f.getLength() + ")" : "TEXT"));
        m.put(LogicalType.DATE, DatabaseTypeMapping.supported("DATE"));
        m.put(LogicalType.TIME, DatabaseTypeMapping.supported("TIME"));
        m.put(LogicalType.TIMESTAMP, DatabaseTypeMapping.supported("TIMESTAMP"));
        m.put(LogicalType.BINARY, DatabaseTypeMapping.supported("BYTEA"));
        m.put(LogicalType.OFFSET_TIME, DatabaseTypeMapping.supported("TIME WITH TIME ZONE"));
        m.put(LogicalType.OFFSET_TIMESTAMP, DatabaseTypeMapping.supported("TIMESTAMP WITH TIME ZONE"));
        requireCompleteMappings(m);
        return Collections.unmodifiableMap(m);
    }
}
